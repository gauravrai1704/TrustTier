const { expect } = require("chai");
const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

// This test uses REAL artifacts from the actual EZKL pipeline:
//   - contracts/EzklVerifier.sol   - the real generated verifier contract
//   - circuits/calldata.bytes      - ready-to-send ABI-encoded calldata for
//                                     verifyProof(bytes,uint256[]), produced
//                                     by ezkl.encode_evm_calldata()
//
// We deliberately send the calldata EZKL itself produced, rather than
// hand-decoding proof.json's `instances` field and re-encoding it
// ourselves: those instances are stored as raw little-endian field
// elements internal to EZKL's own representation, not directly usable as
// Solidity uint256 values without a conversion this test has no need to
// reimplement when EZKL already provides the exact encoded calldata.
//
// This is the Weeks 3-5 milestone: "a real zk-SNARK proof is generated
// off-chain and verified on-chain."
describe("EzklVerifier (real zk-SNARK, generated by the actual EZKL pipeline)", function () {
  let verifier;
  let calldata;
  let owner;

  before(function () {
    const calldataPath = path.join(__dirname, "..", "circuits", "calldata.bytes");
    if (!fs.existsSync(calldataPath)) {
      this.skip(); // circuits/calldata.bytes is a generated artifact - skip gracefully if absent
    }
    calldata = "0x" + fs.readFileSync(calldataPath).toString("hex");
  });

  beforeEach(async function () {
    [owner] = await ethers.getSigners();
    const Verifier = await ethers.getContractFactory("Halo2Verifier");
    verifier = await Verifier.deploy();
  });

  it("verifies the real proof on-chain via a static call and returns true", async function () {
    const result = await owner.call({ to: await verifier.getAddress(), data: calldata });
    // A successful verifyProof call ABI-encodes `true` as its return data.
    const decoded = ethers.AbiCoder.defaultAbiCoder().decode(["bool"], result);
    expect(decoded[0]).to.equal(true);
  });

  it("actually executes on-chain (a real transaction, not just a static call) with realistic gas usage", async function () {
    const tx = await owner.sendTransaction({ to: await verifier.getAddress(), data: calldata });
    const receipt = await tx.wait();

    expect(receipt.status).to.equal(1);
    console.log(`      (on-chain zk-SNARK verification gas used: ${receipt.gasUsed})`);
  });

  it("rejects tampered calldata", async function () {
    // Flip a byte well into the proof portion of the calldata (past the
    // 4-byte selector and offset/length words) - should no longer verify.
    const bytes = ethers.getBytes(calldata);
    bytes[200] ^= 0xff;
    const tampered = ethers.hexlify(bytes);

    await expect(
      owner.sendTransaction({ to: await verifier.getAddress(), data: tampered })
    ).to.be.reverted;
  });
});
